#!/usr/bin/env node
/**
 * generate-icons.mjs — build the inline icon data for <Icon />.
 *
 * WHY THIS EXISTS (root cause, 13 Nov 2026): the app used to render the
 * outline kit SVGs as <img src="/assets/icons/*.svg">. An SVG loaded through
 * <img> is an isolated document — the page's CSS `color` never reaches it,
 * so `stroke="currentColor"` inside the file resolved to the SVG initial
 * colour (black) and every kit icon rendered black on dark glass. The only
 * icons that ever rendered correctly were the four inline ones.
 *
 * The fix is to render UI icons as real inline <svg> so `currentColor`
 * genuinely inherits the button/nav CSS colour (default #D6E3F8 dark,
 * hover #A7BEFF, active #B9A2FF — see glass-navy-tokens.css). Source logos
 * (Gmail, CUIMS, Tasks, System, Webhook, Web Push) are NOT in this module:
 * they stay full-colour <img> in SourceIcon.tsx and must never be touched
 * by icon CSS.
 *
 * This script reads every *.svg in public/assets/icons/ (the canonical
 * asset set — new Glass Navy pack files plus the older outline files that
 * have no pack equivalent) and emits src/components/iconData.generated.ts
 * with { viewBox, body } per file (keyed by file name without .svg).
 * It runs automatically before every build via the `prebuild` script.
 *
 * Transformations per file:
 * - strip <title>/<desc> (decorative icons are aria-hidden; names live on
 *   the button), strip width/height on the root element
 * - rewrite the pack's baked light stroke #D6E3F8 -> currentColor, so the
 *   icon follows its context (dark/light theme, hover, active, disabled)
 * - keep every other colour verbatim (e.g. the coral #FF758F dot in
 *   notification-dot.svg)
 *
 * Safety: refuses any file containing <script, event-handler attributes,
 * external references, or black fills/strokes.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'public', 'assets', 'icons');
const outFile = join(root, 'src', 'components', 'iconData.generated.ts');

const files = readdirSync(iconsDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const data = {};
for (const file of files) {
  const raw = readFileSync(join(iconsDir, file), 'utf8');
  if (/<script/i.test(raw) || /\son\w+\s*=/.test(raw) || /xlink:href|href\s*=/.test(raw)) {
    throw new Error(`${file}: rejected — script, handler or external reference`);
  }
  if (/stroke\s*=\s*["'](#000|black)["']/i.test(raw) || /fill\s*=\s*["'](#000|black)["']/i.test(raw)) {
    throw new Error(`${file}: rejected — black fill/stroke`);
  }
  const viewBox = raw.match(/viewBox\s*=\s*"([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${file}: no viewBox`);
  let body = raw
    .replace(/<svg[^>]*>/i, '')
    .replace(/<\/svg\s*>/i, '')
    .replace(/<title[^>]*>.*?<\/title>/gis, '')
    .replace(/<desc[^>]*>.*?<\/desc>/gis, '')
    .replace(/#D6E3F8/gi, 'currentColor')
    .trim()
    .replace(/\s+/g, ' ');
  if (/<title|<desc/i.test(body)) throw new Error(`${file}: title/desc not stripped`);
  if (/#D6E3F8/i.test(body)) throw new Error(`${file}: baked light stroke survived`);
  data[basename(file, '.svg')] = { viewBox, body };
}

const header = `// GENERATED by scripts/generate-icons.mjs from public/assets/icons/*.svg.
// Do not edit by hand — change the SVG file and re-run the script (it also
// runs automatically via the "prebuild" script). See the script header for
// why UI icons are inline SVG instead of <img> (the black-icons root cause).
// Source logos are NOT here — see SourceIcon.tsx.
`;
const ts =
  header +
  `export interface IconData { viewBox: string; body: string; }\n\n` +
  `export const ICON_DATA: Record<string, IconData> = ${JSON.stringify(data, null, 2)};\n`;

writeFileSync(outFile, ts);
console.log(`generate-icons: ${files.length} icons -> ${outFile}`);
